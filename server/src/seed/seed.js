const log = (...a) => console.log('•', ...a); // eslint-disable-line no-console
const slugify = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const COLORS = ['#6366f1', '#ef4444', '#0ea5e9', '#8b5cf6', '#f59e0b', '#14b8a6', '#64748b', '#ec4899', '#22c55e', '#06b6d4', '#a855f7', '#f97316', '#3b82f6', '#e11d48', '#71717a'];
const day = 86400000;
const at = (offsetDays, hour = 17, minute = 0) => {
  const d = new Date(Date.now() + offsetDays * day);
  d.setHours(hour, minute, 0, 0);
  return d;
};
const pick = (arr, i) => arr[i % arr.length];

async function seedBase() {
  for (const key of PERMISSIONS) {
    await M.Permission.updateOne({ key }, { $set: { key, group: key.split(':')[0], description: key.replace(':', ' → ').replace(/_/g, ' ') } }, { upsert: true });
  }
  log(`${PERMISSIONS.length} permissions`);

  for (const r of DEFAULT_ROLES) {
    await M.Role.updateOne({ key: r.key }, { $set: { name: r.name, description: r.description, isSystem: true, permissions: r.permissions } }, { upsert: true });
  }
  log(`${DEFAULT_ROLES.length} system roles`);

  for (const [i, name] of DEFAULT_CATEGORIES.entries()) {
    await M.TaskCategory.updateOne({ slug: slugify(name), department: null }, { $setOnInsert: { name, slug: slugify(name), color: COLORS[i % COLORS.length], department: null, isDefault: true } }, { upsert: true });
  }
  log(`${DEFAULT_CATEGORIES.length} default task categories`);

  const superRole = await M.Role.findOne({ key: 'super_admin' });
  let admin = await M.User.findOne({ email: env.superAdmin.email }).setOptions({ withDeleted: true });
  if (!admin) {
    admin = new M.User({ name: env.superAdmin.name, email: env.superAdmin.email, roles: [superRole._id], designation: 'System Administrator', mustChangePassword: env.isProd });
    await admin.setPassword(env.superAdmin.password);
    await admin.save();
    log(`Super Admin created: ${env.superAdmin.email}`);
  } else {
    log(`Super Admin exists: ${env.superAdmin.email}`);
  }
  return admin;
}

