/**
 * Seed script.
 *   npm run seed            -> roles, permissions, default categories, Super Admin (idempotent)
 *   npm run seed -- --demo  -> also creates a demo CSE department with realistic data
 *   npm run seed -- --reset --demo  -> DROPS the database first (development only)
 */
